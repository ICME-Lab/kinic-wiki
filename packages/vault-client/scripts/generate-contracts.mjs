// Generated types are narrow; the full Wiki IDL is the only browser runtime IDL.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../../", import.meta.url));
const adapter = readFileSync(`${root}wikibrowser/app/vault/actor.ts`, "utf8");
const methodSection = adapter.slice(
  adapter.indexOf("export const vaultMethods"),
  adapter.indexOf("] as const"),
);
const names = new Set(
  [...methodSection.matchAll(/"([a-z_]+)"/g)].map(
    (match) => `vault_${match[1]}`,
  ),
);
const generated = execFileSync(
  "didc",
  ["bind", `${root}crates/vfs_canister/vfs.did`, "--target", "ts"],
  { encoding: "utf8" },
);
const starts = [...generated.matchAll(/^export (?:interface|type) (\w+)\b/gm)];
const declarations = new Map(
  starts.map((match, i) => [
    match[1],
    generated
      .slice(
        match.index,
        starts[i + 1]?.index ?? generated.indexOf("export declare"),
      )
      .trim(),
  ]),
);
const service = declarations.get("_SERVICE");
if (!service?.startsWith("export interface _SERVICE {"))
  throw Error("Missing generated service");
const chunks = service
  .slice(service.indexOf("\n") + 1, service.lastIndexOf("}"))
  .split(/(?=^  ')/m)
  .filter(Boolean);
const methods = chunks.filter((chunk) =>
  names.has(chunk.match(/^  '([^']+)'/)?.[1]),
);
if (methods.length !== names.size)
  throw Error("Vault adapter method does not exist in generated Wiki Candid");
const required = new Set();
function collect(text) {
  for (const token of text.matchAll(/\b[A-Z]\w*\b/g)) {
    if (declarations.has(token[0]) && !required.has(token[0])) {
      required.add(token[0]);
      collect(declarations.get(token[0]));
    }
  }
}
collect(methods.join(""));
const text =
  "// Generated by scripts/generate-contracts.mjs from the integrated Wiki Candid.\n" +
  "import type { ActorMethod } from '@icp-sdk/core/agent';\n\n" +
  [...declarations]
    .filter(([name]) => required.has(name))
    .map(([, value]) => value)
    .join("\n") +
  "\nexport interface _SERVICE {\n" +
  methods.join("") +
  "}\n\n" +
  "// Runtime IDL comes exclusively from @kinic/vfs-candid.\n" +
  "export type VaultActor = { [K in keyof _SERVICE as K extends `vault_${infer Name}` ? Name : never]: _SERVICE[K] };\n";
const target = `${root}packages/vault-client/src/contracts.ts`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== text)
    throw Error(
      "Vault DTO drift: run node packages/vault-client/scripts/generate-contracts.mjs",
    );
  console.log(`Vault DTOs match ${names.size} integrated Candid methods`);
} else writeFileSync(target, text);
